"""Generate Tables 1-4, Figures 1-8, and unaggregated run data.

Every experiment is read from a JSON manifest. The manuscript manifest uses
the reported run/period counts; the smoke manifest uses the same code paths
with smaller counts for CI. Outputs are never treated as historical v3.2 data:
they are regenerated by the corrected, specification-aligned implementation.
"""

