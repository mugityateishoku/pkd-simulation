    def sensitivity(self) -> list[dict[str, Any]]:
        spec = self.manifest["experiments"]["sensitivity"]
        rows: list[dict[str, Any]] = []
        for parameter, values in spec["grids"].items():
            for value in values:
                updates: dict[str, Any] = {"n_periods": int(spec["periods"])}
                if parameter == "demagogue_fraction":
                    n_demagogues = int(round(self.base.population_size * float(value)))
                    updates.update(
                        n_demagogues=n_demagogues,
                        n_citizens=self.base.population_size
                        - self.base.n_experts
                        - n_demagogues,
                    )
                elif parameter == "seats_per_pool":
                    seats = int(value)
                    updates.update(
                        n_expert_seats=seats,
                        n_citizen_seats=seats,
                        sortition_size=2 * seats,
                    )
                else:
                    updates[parameter] = value
                config = self.base.with_updates(**updates)
                label = f"sensitivity_{parameter}_{value}"
                results = self.run_condition(label, config, int(spec["runs"]))
                for row in _aggregate(results):
                    rows.append(
                        {
                            "parameter": parameter,
                            "value": value,
                            "system": row["system"],
                            "mean_performance": row["mean_performance"],
                            "ci95_low": row["ci95_low"],
                            "ci95_high": row["ci95_high"],
                            "mean_demagogue_fraction": row[
                                "mean_demagogue_fraction"
                            ],
                        }
                    )
        write_csv(self.raw_dir / "figure3_sensitivity.csv", rows)

        import matplotlib.pyplot as plt

        parameters = list(spec["grids"])
        fig, axes = plt.subplots(2, 4, figsize=(17, 8))
        for axis, parameter in zip(axes.flat, parameters):
            subset = [row for row in rows if row["parameter"] == parameter]
            for system in (SYSTEM_APPEAL, SYSTEM_SORTITION, SYSTEM_PKD):
                system_rows = [row for row in subset if row["system"] == system]
                axis.plot(
                    [float(row["value"]) for row in system_rows],
                    [row["mean_performance"] for row in system_rows],
                    marker="o", label=system,
                )
            axis.set_title(parameter.replace("_", " "))
            axis.grid(alpha=0.2)
        axes.flat[-1].axis("off")
        axes.flat[0].legend(fontsize=7)
        fig.tight_layout()
        self.save_figure(3, fig, "figure3_sensitivity", "raw/sensitivity_*")
        plt.close(fig)

        fraction_rows = [row for row in rows if row["parameter"] == "demagogue_fraction"]
        fig, axis = plt.subplots(figsize=(7, 5))
        for system in BASELINE_SYSTEMS:
            system_rows = [row for row in fraction_rows if row["system"] == system]
            axis.plot(
                [float(row["value"]) for row in system_rows],
                [row["mean_demagogue_fraction"] for row in system_rows],
                marker="o", label=system,
            )
        axis.plot([0, 0.3], [0, 0.3], color="black", ls="--", label="population share")
        axis.set_xlabel("Demagogue population fraction")
        axis.set_ylabel("Council fraction")
        axis.grid(alpha=0.2)
        axis.legend(fontsize=7)
        fig.tight_layout()
        self.save_figure(4, fig, "figure4_infiltration", "raw/sensitivity_demagogue_fraction_*")
        plt.close(fig)
        return rows

