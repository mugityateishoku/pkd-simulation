def _slug(value: str) -> str:
    return "".join(ch.lower() if ch.isalnum() else "_" for ch in value).strip("_")


def _seed(base_seed: int, label: str) -> int:
    return int(np.uint32(base_seed) ^ np.uint32(zlib.crc32(label.encode("utf-8"))))


def _mean_ci(values: Sequence[float]) -> tuple[float, float, float]:
    array = np.asarray(values, dtype=float)
    mean = float(array.mean())
    if len(array) < 2:
        return mean, mean, mean
    se = float(array.std(ddof=1) / math.sqrt(len(array)))
    try:
        from scipy import stats

        critical = float(stats.t.ppf(0.975, len(array) - 1))
    except ImportError:
        critical = 1.96
    return mean, mean - critical * se, mean + critical * se


def _run_means(results: Sequence[RunResult]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in summarize_runs(results):
        grouped[str(row["system"])].append(row)
    return grouped


def _aggregate(results: Sequence[RunResult]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for system, system_rows in sorted(_run_means(results).items()):
        mean, low, high = _mean_ci([row["mean_performance"] for row in system_rows])
        pre = float(np.mean([row["pre_shock_performance"] for row in system_rows]))
        post = float(np.mean([row["post_shock_performance"] for row in system_rows]))
        infiltration = float(
            np.mean([row["mean_demagogue_fraction"] for row in system_rows])
        )
        rows.append(
            {
                "system": system,
                "mean_performance": mean,
                "ci95_low": low,
                "ci95_high": high,
                "pre_shock_performance": pre,
                "post_shock_performance": post,
                "post_minus_pre": post - pre,
                "mean_demagogue_fraction": infiltration,
                "n_runs": len(system_rows),
            }
        )
    return rows


def _trajectory(
    results: Sequence[RunResult], system: str, field: str = "performance"
) -> np.ndarray:
    trajectories = []
    for result in results:
        records = result.system_periods(system)
        trajectories.append([getattr(record, field) for record in records])
    return np.asarray(trajectories, dtype=float)


class Reproducer:
    def __init__(self, manifest_path: Path, output_dir: Path):
        self.manifest_path = manifest_path
        self.output_dir = output_dir
        with manifest_path.open("r", encoding="utf-8") as handle:
            self.manifest = json.load(handle)
        self.base = ModelConfig.from_mapping(self.manifest["model"])
        self.base_seed = int(self.manifest["base_seed"])
        self.raw_dir = output_dir / "raw"
        self.tables_dir = output_dir / "tables"
        self.figures_dir = output_dir / "figures"
        self.artifacts: list[dict[str, Any]] = []
        for directory in (self.raw_dir, self.tables_dir, self.figures_dir):
            directory.mkdir(parents=True, exist_ok=True)
        shutil.copy2(manifest_path, output_dir / "resolved_experiment_manifest.json")

    def run_condition(
        self,
        label: str,
        config: ModelConfig,
        n_runs: int,
        *,
        export: bool = True,
    ) -> list[RunResult]:
        results = run_ensemble(
            config,
            n_runs=int(n_runs),
            base_seed=_seed(self.base_seed, label),
        )
        if export:
            export_run_data(results, self.raw_dir / _slug(label))
        return results

    def table(self, number: int, filename: str, rows: Iterable[dict[str, Any]]) -> None:
        path = self.tables_dir / filename
        write_csv(path, rows)
        self.artifacts.append(
            {
                "artifact": f"Table {number}",
                "path": path.relative_to(self.output_dir).as_posix(),
                "generator": "reproduce_all.py",
                "raw_inputs": "raw/baseline",
            }
        )

    def save_figure(self, number: int, figure, stem: str, raw_inputs: str) -> None:
        png = self.figures_dir / f"{stem}.png"
        pdf = self.figures_dir / f"{stem}.pdf"
        figure.savefig(png, dpi=300, bbox_inches="tight")
        figure.savefig(pdf, bbox_inches="tight")
        self.artifacts.append(
            {
                "artifact": f"Figure {number}",
                "path": png.relative_to(self.output_dir).as_posix(),
                "generator": "reproduce_all.py",
                "raw_inputs": raw_inputs,
            }
        )

    def baseline(self) -> list[RunResult]:
        spec = self.manifest["experiments"]["baseline"]
        config = self.base.with_updates(
            n_periods=int(spec["periods"]), include_sortition_deliberation=True
        )
        results = self.run_condition("baseline", config, int(spec["runs"]))
        aggregates = _aggregate(results)
        table1 = [row for row in aggregates if row["system"] in BASELINE_SYSTEMS]
        self.table(1, "table1_baseline.csv", table1)

        archetypes: dict[str, list[Any]] = defaultdict(list)
        for result in results:
            for agent in result.agents:
                archetypes[agent.archetype].append(agent)
        table2 = []
        for archetype, agents in sorted(archetypes.items()):
            table2.append(
                {
                    "archetype": archetype,
                    "mean_track_record": float(
                        np.mean([agent.track_record for agent in agents])
                    ),
                    "mean_tolerance": float(np.mean([agent.tolerance for agent in agents])),
                    "n_agent_runs": len(agents),
                }
            )
        self.table(2, "table2_track_records.csv", table2)

        current = {row["system"]: row for row in aggregates}
        docking_rows = []
        for source, systems in self.manifest.get("docking_reference", {}).items():
            for system, values in systems.items():
                docking_rows.append({"source": source, "system": system, **values})
        for system, row in current.items():
            docking_rows.append(
                {
                    "source": "corrected_specification_run",
                    "system": system,
                    "mean_performance": row["mean_performance"],
                    "post_minus_pre": row["post_minus_pre"],
                    "mean_demagogue_fraction": row["mean_demagogue_fraction"],
                    "status": "regenerated",
                }
            )
        self.table(3, "table3_model_docking.csv", docking_rows)

        grouped = _run_means(results)
        pkd_by_run = {int(row["run"]): float(row["mean_performance"]) for row in grouped[SYSTEM_PKD]}
        table4 = []
        for comparison in (
            SYSTEM_SORTITION,
            SYSTEM_SORTITION_DELIBERATION,
            SYSTEM_APPEAL,
            "Autocracy",
        ):
            comparison_by_run = {
                int(row["run"]): float(row["mean_performance"])
                for row in grouped[comparison]
            }
            runs = sorted(set(pkd_by_run) & set(comparison_by_run))
            differences = np.array(
                [pkd_by_run[index] - comparison_by_run[index] for index in runs]
            )
            mean, low, high = _mean_ci(differences)
            sd = float(differences.std(ddof=1)) if len(differences) > 1 else 0.0
            t_stat = mean / (sd / math.sqrt(len(differences))) if sd else math.inf
            p_paired: float | str = ""
            p_wilcoxon: float | str = ""
            try:
                from scipy import stats

                p_paired = float(stats.ttest_rel(
                    [pkd_by_run[index] for index in runs],
                    [comparison_by_run[index] for index in runs],
                ).pvalue)
                p_wilcoxon = float(stats.wilcoxon(differences).pvalue)
            except ImportError:
                pass
            table4.append(
                {
                    "comparison": f"PKD vs {comparison}",
                    "mean_paired_difference": mean,
                    "ci95_low": low,
                    "ci95_high": high,
                    "paired_t": t_stat,
                    "p_paired_t": p_paired,
                    "p_wilcoxon": p_wilcoxon,
                    "cohens_dz": mean / sd if sd else math.inf,
                    "n_pairs": len(differences),
                }
            )
        self.table(4, "table4_paired_inference.csv", table4)
        return results

